// npm run scoreboard:snapshot: renders Dhwanil's scoreboard from the newest committed results in evals/results/
// and writes it into src/scoreboard-snapshot.ts, so a deployed build serves the numbers at /scoreboard without the
// raw result files. Run it (and commit the file) after new eval results land; a test fails until you do.
import { writeFileSync } from "node:fs";
import { renderLatestScoreboard } from "../evals/scoreboard.js";

const html = renderLatestScoreboard();
const file = new URL("../src/scoreboard-snapshot.ts", import.meta.url);
writeFileSync(
  file,
  `// Generated by npm run scoreboard:snapshot from the newest files in evals/results/. Do not edit by hand.\nexport const SCOREBOARD_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`Wrote src/scoreboard-snapshot.ts (${html.length} characters)`);
